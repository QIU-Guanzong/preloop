"""Contract tests for the flow to flow delegation object shapes.

These tests are the freeze. They assert that the shapes a delegated call
uses (the request a parent sends, the task record a child is represented
by, the artifact a child result becomes) match the document under
``docs/guide/flow-delegation-shapes.md`` and the JSON schemas shipped
beside the helper, so a later child of #621 cannot quietly invent a
second field vocabulary.

No runtime behaviour is exercised: the module under test loads JSON and
validates dictionaries.
"""

