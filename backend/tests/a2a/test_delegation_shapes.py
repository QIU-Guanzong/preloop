def _doc_text() -> str:
    return DOC_PATH.read_text(encoding="utf-8")


def _doc_examples(marker: str) -> List[Dict[str, Any]]:
    """JSON blocks the document tags with ``<!-- validates: <marker> -->``."""
    pattern = re.compile(
        r"<!--\s*validates:\s*" + re.escape(marker) + r"\s*-->\s*```json\n(.*?)```",
        re.DOTALL,
    )
    return [json.loads(block) for block in pattern.findall(_doc_text())]


class TestSchemasValidateTheExamples:
    def test_request_example_is_valid(self) -> None:
        validate_delegation_request(REQUEST_EXAMPLE)

    def test_task_example_is_valid(self) -> None:
        validate_delegation_task(TASK_EXAMPLE)

    def test_refusal_example_is_valid(self) -> None:
        validate_delegation_task(REFUSAL_EXAMPLE)

    def test_request_without_a_part_is_rejected(self) -> None:
        payload = json.loads(json.dumps(REQUEST_EXAMPLE))
        payload["parts"] = []
        with pytest.raises(DelegationShapeError):
            validate_delegation_request(payload)

    def test_request_with_agent_role_is_rejected(self) -> None:
        payload = json.loads(json.dumps(REQUEST_EXAMPLE))
        payload["role"] = "ROLE_AGENT"
        with pytest.raises(DelegationShapeError):
            validate_delegation_request(payload)

    def test_request_with_an_unknown_metadata_key_is_rejected(self) -> None:
        payload = json.loads(json.dumps(REQUEST_EXAMPLE))
        payload["metadata"]["preloop.ai/budgetCeiling"] = 5
        with pytest.raises(DelegationShapeError):
            validate_delegation_request(payload)

    def test_request_may_not_claim_a_child_execution_id(self) -> None:
        payload = json.loads(json.dumps(REQUEST_EXAMPLE))
        payload["metadata"]["preloop.ai/executionId"] = TASK_EXAMPLE["id"]
        with pytest.raises(DelegationShapeError):
            validate_delegation_request(payload)

    def test_task_without_an_execution_id_is_rejected(self) -> None:
        payload = json.loads(json.dumps(TASK_EXAMPLE))
        del payload["metadata"]["preloop.ai/executionId"]
        with pytest.raises(DelegationShapeError):
            validate_delegation_task(payload)

    def test_refusal_without_a_reason_is_rejected(self) -> None:
        payload = json.loads(json.dumps(REFUSAL_EXAMPLE))
        del payload["metadata"]["preloop.ai/refusalReason"]
        with pytest.raises(DelegationShapeError):
            validate_delegation_task(payload)

    def test_refusal_reason_is_from_the_frozen_list(self) -> None:
        payload = json.loads(json.dumps(REFUSAL_EXAMPLE))
        payload["metadata"]["preloop.ai/refusalReason"] = "because_i_said_so"
        with pytest.raises(DelegationShapeError):
            validate_delegation_task(payload)

    def test_task_with_an_unknown_state_is_rejected(self) -> None:
        payload = json.loads(json.dumps(TASK_EXAMPLE))
        payload["status"]["state"] = "completed"
        with pytest.raises(DelegationShapeError):
            validate_delegation_task(payload)


class TestStatusMapping:
    """One case per Preloop execution status, refusal included."""

    EXPECTED = {
        "PENDING": "TASK_STATE_SUBMITTED",
        "INITIALIZING": "TASK_STATE_SUBMITTED",
        "STARTING": "TASK_STATE_SUBMITTED",
        "RUNNING": "TASK_STATE_WORKING",
        "RESUMING": "TASK_STATE_WORKING",
        "WAITING_FOR_HUMAN": "TASK_STATE_INPUT_REQUIRED",
        "WAITING_FOR_CHILDREN": "TASK_STATE_WORKING",
        "SUCCEEDED": "TASK_STATE_COMPLETED",
        "FAILED": "TASK_STATE_FAILED",
        "TIMEOUT": "TASK_STATE_FAILED",
        "TIMED_OUT": "TASK_STATE_FAILED",
        "ABORTED": "TASK_STATE_FAILED",
        "STOPPED": "TASK_STATE_CANCELED",
        "CANCELLED": "TASK_STATE_CANCELED",
        "CANCELED": "TASK_STATE_CANCELED",
        "REFUSED": "TASK_STATE_REJECTED",
    }

    @pytest.mark.parametrize("status,state", sorted(EXPECTED.items()))
    def test_each_status_maps(self, status: str, state: str) -> None:
        assert task_state_for_status(status) == state

    def test_table_has_no_extra_rows(self) -> None:
        assert dict(STATUS_TO_TASK_STATE) == self.EXPECTED

    def test_refusal_is_not_a_failure(self) -> None:
        assert task_state_for_status(REFUSED_STATUS) == "TASK_STATE_REJECTED"
        assert task_state_for_status("FAILED") == "TASK_STATE_FAILED"
        assert task_state_for_status(REFUSED_STATUS) != task_state_for_status("FAILED")
        assert is_refusal(REFUSED_STATUS)
        assert not is_refusal("FAILED")

    def test_unknown_status_raises_rather_than_guessing(self) -> None:
        with pytest.raises(DelegationShapeError):
            task_state_for_status("WAITING_FOR_A_STATUS_NOBODY_ADDED")

    def test_every_mapped_state_is_an_a2a_state(self) -> None:
        a2a_states = {
            "TASK_STATE_UNSPECIFIED",
            "TASK_STATE_SUBMITTED",
            "TASK_STATE_WORKING",
            "TASK_STATE_COMPLETED",
            "TASK_STATE_FAILED",
            "TASK_STATE_CANCELED",
            "TASK_STATE_INPUT_REQUIRED",
            "TASK_STATE_REJECTED",
            "TASK_STATE_AUTH_REQUIRED",
        }
        assert set(STATUS_TO_TASK_STATE.values()) <= a2a_states


class TestDocumentAndSchemaAgree:
    def test_document_exists_and_disclaims_a2a_support(self) -> None:
        text = _doc_text().lower()
        assert "not a2a support" in text
        assert "no json-rpc endpoint" in text
        assert "no agent card" in text

    def test_document_cites_the_normative_version_and_binding(self) -> None:
        text = _doc_text()
        assert A2A_SPECIFICATION_VERSION in text
        assert f"protocol version {A2A_PROTOCOL_VERSION}" in text.lower()
        assert A2A_PROTOCOL_BINDING in text

    def test_load_schema_returns_a_copy(self) -> None:
        first = load_schema("delegation_request")
        first["poison"] = True
        second = load_schema("delegation_request")
        assert "poison" not in second

    def test_metadata_key_list_matches_the_schemas(self) -> None:
        request_keys = set(
            load_schema("delegation_request")["$defs"]["requestMetadata"]["properties"]
        )
        task_keys = set(
            load_schema("delegation_task")["$defs"]["taskMetadata"]["properties"]
        )
        assert request_keys | task_keys == set(DELEGATION_METADATA_KEYS)

    def test_metadata_key_list_matches_the_document(self) -> None:
        documented = set(re.findall(r"`(preloop\.ai/[A-Za-z]+)`", _doc_text()))
        assert documented == set(DELEGATION_METADATA_KEYS)

    def test_status_table_in_the_document_matches_the_code(self) -> None:
        rows = re.findall(
            r"^\|\s*`([A-Z_]+)`\s*\|\s*`(TASK_STATE_[A-Z_]+)`\s*\|",
            _doc_text(),
            re.MULTILINE,
        )
        assert dict(rows) == dict(STATUS_TO_TASK_STATE)

    def test_refusal_reasons_in_the_document_match_the_schema(self) -> None:
        documented = set(re.findall(r"^\|\s*`([a-z_]+)`\s*\|", _doc_text(), re.M))
        assert set(REFUSAL_REASONS) <= documented

    def test_document_examples_validate(self) -> None:
        requests = _doc_examples("delegation_request")
        tasks = _doc_examples("delegation_task")
        assert requests, "the document shows no request example"
        assert tasks, "the document shows fewer than two task examples"
        for example in requests:
            validate_delegation_request(example)
        for example in tasks:
            validate_delegation_task(example)
